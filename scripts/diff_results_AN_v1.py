"""Diff report (AN_v1): which Paper B numbers moved between two results manifests, and why.

    python scripts/diff_results_AN_v1.py OLD.json NEW.json --out docs/DIFF_<name>_AN_v1.md [--tol 0.005]

"Why" is assembled only from recorded evidence, never guessed:
  * code: commit change, plus `git log OLD..NEW` subjects touching each step's script and repo inputs;
  * inputs: per-step SHA-256 changes (changed / added / removed files, including the raw downloads);
  * parameter file: version change and a key-level diff of the two ipcc_params CSVs (added / removed / value changed);
  * environment: package-version changes; upstream pins: fingerprint changes.
Each moved number is tagged with the step that produced it and that step's changed inputs.
Numbers moving by <= --tol (absolute) are listed as unchanged.
"""
from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(*a):
    r = subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def norm(p):
    return str(p).replace("\\", "/")


def params_diff(pa, pb):
    def load(p):
        f = ROOT / p
        if not f.exists():
            return None
        with open(f, encoding="utf-8", newline="") as fh:
            return {r["key"]: r for r in csv.DictReader(fh)}
    a, b = load(pa), load(pb)
    if a is None or b is None:
        return None
    ch = sorted(k for k in a.keys() & b.keys() if a[k]["value"] != b[k]["value"])
    return {"added": sorted(b.keys() - a.keys()), "removed": sorted(a.keys() - b.keys()),
            "value_changed": [(k, a[k]["value"], b[k]["value"]) for k in ch]}


def step_of(m, key):
    for s in m["steps"]:
        if key in s.get("paper_numbers", []):
            return s["name"]
    return None


def fmt(x):
    return "" if x is None else (f"{x:,.3f}".rstrip("0").rstrip(".") if isinstance(x, float) else str(x))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("old")
    ap.add_argument("new")
    ap.add_argument("--out", required=True)
    ap.add_argument("--tol", type=float, default=0.005)
    a = ap.parse_args(argv)
    A, B = (json.loads(Path(p).read_text(encoding="utf-8")) for p in (a.old, a.new))
    out = Path(a.out)
    if out.exists():
        sys.exit(f"refusing to overwrite {out}")
    L = [f"# Results diff: `{Path(a.old).name}` -> `{Path(a.new).name}`", "",
         "Generated by `scripts/diff_results_AN_v1.py`. Causes below are taken from recorded hashes, commits and",
         "parameter files only. Comparisons with EPA or field data are consistency checks, not validation.", ""]
    for k, lab in (("aliases_note", "Key mapping"),):
        for m, n in ((A, "old"), (B, "new")):
            if m.get(k):
                L.append(f"- **{lab} ({n}):** {m[k]}")
    ca, cb = A["code"]["commit"], B["code"]["commit"]
    L += ["", "## Why: what changed between the two runs", "",
          f"- **Code commit:** `{ca[:7]}` ({A.get('generated', '?')}) -> `{cb[:7]}` ({B.get('generated', '?')})"]
    pa, pb = A["parameter_file"], B["parameter_file"]
    if pa["sha256"] != pb["sha256"]:
        L.append(f"- **Parameter file:** `{norm(pa['path'])}` -> `{norm(pb['path'])}`")
        d = params_diff(norm(pa["path"]), norm(pb["path"]))
        if d:
            L.append(f"  - {len(d['added'])} keys added, {len(d['removed'])} removed, {len(d['value_changed'])} values changed")
            if d["added"]:
                pref = sorted({k.rsplit('.', 1)[0] for k in d["added"]})
                L.append(f"  - added key families ({len(pref)}): " + ", ".join(f"`{p}`" for p in pref[:25]) + (" ..." if len(pref) > 25 else ""))
            for k, x, y in d["value_changed"][:25]:
                L.append(f"  - `{k}`: {x} -> {y}")
    else:
        L.append(f"- **Parameter file:** unchanged (`{norm(pb['path'])}`)")
    pk = sorted(k for k in set(A.get("packages", {})) | set(B.get("packages", {}))
                if A.get("packages", {}).get(k) != B.get("packages", {}).get(k))
    L.append("- **Packages:** " + (", ".join(f"{k} {A['packages'].get(k)} -> {B['packages'].get(k)}" for k in pk) or "unchanged / not recorded"))
    ua, ub = (m.get("upstream_sources") or {} for m in (A, B))
    up = sorted(k for k in set(ua.get("pins", {}).get("sources", {})) | set(ub.get("pins", {}).get("sources", {}))
                if ua.get("pins", {}).get("sources", {}).get(k) != ub.get("pins", {}).get("sources", {}).get(k))
    L.append("- **Upstream pins:** " + (", ".join(up) if up else "unchanged / not recorded"))
    sa = {s["name"]: s for s in A["steps"]}
    causes = {}
    L += ["", "### Per step", ""]
    for s in B["steps"]:
        o = sa.get(s["name"])
        if o is None:
            L.append(f"- **{s['name']}**: new step")
            continue
        ia, ib = {norm(k): v for k, v in o["inputs_sha256"].items()}, {norm(k): v for k, v in s["inputs_sha256"].items()}
        ch = [f"`{k}` changed" for k in sorted(ia.keys() & ib.keys()) if ia[k] != ib[k]]
        ch += [f"`{k}` added" for k in sorted(ib.keys() - ia.keys())] + [f"`{k}` removed" for k in sorted(ia.keys() - ib.keys())]
        if o.get("script") != s.get("script") or o.get("script_sha256") != s.get("script_sha256"):
            ch.insert(0, f"script `{o.get('script')}` -> `{s.get('script')}`" if o.get("script") != s.get("script") else f"script `{s['script']}` edited")
        paths = [p for p in {o.get("script"), s.get("script"), *[k for k in ib if not k.startswith("RAW:")]} if p]
        logs = git("log", "--format=%h %s", f"{ca}..{cb}", "--", *paths).splitlines() if ca and cb else []
        causes[s["name"]] = ch
        L.append(f"- **{s['name']}**: " + ("; ".join(ch) if ch else "no input or script change"))
        for g in logs[:10]:
            L.append(f"  - commit {g}")
    na, nb = A["paper_numbers"], B["paper_numbers"]
    moved, same = [], 0
    for k in sorted(na.keys() | nb.keys()):
        x, y = na.get(k), nb.get(k)
        if x is not None and y is not None and abs(y - x) <= a.tol:
            same += 1
            continue
        moved.append((k, x, y))
    L += ["", f"## Paper numbers that moved ({len(moved)} moved or new/removed; {same} unchanged within {a.tol})", "",
          "| number | old | new | change | % | step |", "|---|---|---|---|---|---|"]
    for k, x, y in moved:
        d = "" if x is None or y is None else y - x
        pc = "" if not x or y is None else f"{100 * (y - x) / abs(x):+.1f}"
        st = step_of(B, k) or step_of(A, k) or ""
        L.append(f"| `{k}` | {fmt(x) if x is not None else 'new'} | {fmt(y) if y is not None else 'removed'} | "
                 f"{fmt(d) if d != '' else ''} | {pc} | {st} |")
    L += ["", "Step causes are listed under *Per step* above; every number in a step inherits them."]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", out, f"({len(moved)} moved, {same} unchanged)")


if __name__ == "__main__":
    main()